type Health = { label: string; cls: string; hint?: string };
function healthOf(p: LLMProfile, m?: LLMPoolMember): Health {
  if (!p.api_key_hint) {
    return {
      label: "English textConfiguration Key",
      cls: "border-muted-foreground/40 text-muted-foreground",
      hint: "English text API Key，English text",
    };
  }
  if (m?.state === "tripped") {
    return {
      label: m.cooldown_secs > 0 ? `English text · ${cooldownText(m.cooldown_secs)}` : "English text",
      cls: "border-destructive/50 text-destructive",
      hint: m.last_error,
    };
  }
  if (m?.state === "degraded") {
    return {
      label: `English text · Failed ${m.fails} English text`,
      cls: "border-amber-500/50 text-amber-600 dark:text-amber-400",
      hint: m.last_error,
    };
  }
  return { label: "English text", cls: "border-emerald-500/50 text-emerald-600 dark:text-emerald-400" };
}

